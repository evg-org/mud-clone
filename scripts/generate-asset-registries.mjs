import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const checkOnly = process.argv.includes("--check");

function toPosixPath(value) {
  return value.split(sep).join("/");
}

function walkFiles(root) {
  const entries = readdirSync(root, { withFileTypes: true }).sort((a, b) =>
    a.name.localeCompare(b.name),
  );
  const files = [];

  for (const entry of entries) {
    const absolutePath = resolve(root, entry.name);

    if (entry.isDirectory()) {
      files.push(...walkFiles(absolutePath));
      continue;
    }

    if (entry.isFile()) {
      files.push(absolutePath);
    }
  }

  return files;
}

function createRegistry({
  assetRoot,
  exportNames,
  outputFile,
  extensions,
  exclude = new Set(),
}) {
  const absoluteAssetRoot = resolve(packageRoot, assetRoot);
  const absoluteOutputFile = resolve(packageRoot, outputFile);
  const outputDir = dirname(absoluteOutputFile);
  const registry = new Map();

  for (const file of walkFiles(absoluteAssetRoot)) {
    const relativeFile = toPosixPath(relative(absoluteAssetRoot, file));
    const extension = extensions.find((item) => relativeFile.endsWith(item));

    if (!extension || exclude.has(relativeFile)) {
      continue;
    }

    const name = relativeFile.slice(0, -extension.length);
    const importPath = toPosixPath(
      relative(outputDir, resolve(absoluteAssetRoot, relativeFile)),
    );
    const normalizedImportPath = importPath.startsWith(".")
      ? importPath
      : `./${importPath}`;
    const assetExpression =
      `new URL(${JSON.stringify(normalizedImportPath)}, import.meta.url).href`;

    registry.set(name, assetExpression);

    const lowerName = name.toLowerCase();

    if (!registry.has(lowerName)) {
      registry.set(lowerName, assetExpression);
    }
  }

  const [registryName, namesName] = exportNames;
  const objectEntries = [...registry.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([name, expression]) => `  ${JSON.stringify(name)}: ${expression},`)
    .join("\n");
  const content = `/* This file is generated by scripts/generate-asset-registries.mjs. Do not edit manually. */

const ${registryName} = {
${objectEntries}
} as const satisfies Record<string, string>;

const ${namesName} = Object.keys(${registryName}).sort();

export { ${registryName}, ${namesName} };
`;

  if (checkOnly) {
    const existing = readFileSync(absoluteOutputFile, "utf8");

    if (existing !== content) {
      throw new Error(`${outputFile} is out of date. Run npm run generate:assets.`);
    }

    return;
  }

  mkdirSync(outputDir, { recursive: true });
  writeFileSync(absoluteOutputFile, content);
}

createRegistry({
  assetRoot: "src/assets/mud/icons",
  exclude: new Set(["sprite.svg"]),
  exportNames: ["mudIcons", "mudIconNames"],
  extensions: [".svg"],
  outputFile: "src/generated/mud-icons.ts",
});

createRegistry({
  assetRoot: "src/assets/mud/logos",
  exportNames: ["mudLogos", "mudLogoNames"],
  extensions: [".svg", ".png"],
  outputFile: "src/generated/mud-logos.ts",
});

console.log(
  checkOnly
    ? "Generated asset registries are up to date."
    : "Generated asset registries.",
);
